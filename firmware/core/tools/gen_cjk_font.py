#!/usr/bin/env python3
"""Bake the firmware's CJK bitmap font (src/font_cjk.cpp).

16x16 one-bit-per-pixel glyphs for GB2312 level-1 hanzi plus common CJK
punctuation, rendered from Noto Sans CJK SC. Run on a machine that has the
font and Pillow; the generated .cpp is committed so builds need neither.

    python3 gen_cjk_font.py            # writes font_cjk.cpp next to this file

Glyphs render at 64 px and downsample to 16x16 (box filter, then threshold),
which keeps strokes at a sane weight; ASCII-art previews are printed for a
handful of characters so the result can be eyeballed after every bake.
"""

import sys
from pathlib import Path

from PIL import Image, ImageFont

FONT = "/usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc"
OUT = Path(__file__).resolve().parent / "font_cjk.cpp"
CELL = 16          # final bitmap size
SS = 8             # supersample factor (128 px render)
THRESHOLD = 128
# The ideographic em box sits from about -0.86 em to +0.08 em around the
# baseline; center it in the cell by putting the baseline 0.39 em below the
# middle. Anchor "mm" would center the (much taller) line box instead and
# clip dense glyphs at the bottom.
BASELINE_SHIFT_EM = 0.39

# GB2312 level-1: rows 0xB0..0xD7, columns 0xA1..0xFE (3755 hanzi).
def gb2312_level1():
    out = []
    for zone in range(0xB0, 0xD8):
        for pos in range(0xA1, 0xFF):
            try:
                out.append(bytes([zone, pos]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return out

# Common full-width punctuation and symbols seen in agent replies.
PUNCT = (
    "\uFF0C\u3002\u3001\uFF01\uFF1F\uFF1A\uFF1B\u00B7"   # ，。、！？：；·
    "\u201C\u201D\u2018\u2019"                              # \u201c \u201d \u2018 \u2019
    "\uFF08\uFF09\u300A\u300B\u3008\u3009\u3010\u3011"   # （）《》〈〉【】
    "\u3014\u3015\u300C\u300D\u300E\u300F"                 # 〔〕「」『』
    "\u2026\u2014\uFF5E\uFFE5\uFF05\uFF0B\uFF1D"          # …—～￥％＋＝
    "\uFF1C\uFF1E\uFF06\uFF20\uFF03\uFF0A\uFF0F"          # ＜＞＆＠＃＊／
    "\uFF3C\uFF5C\uFF3F\uFF0D"                               # ＼｜＿－
)

def render_char(font_big, ch, threshold=THRESHOLD):
    """Return the char as CELLxCELL bits (row-major, MSB first), or None."""
    big = CELL * SS
    img = Image.new("L", (big, big), 0)
    from PIL import ImageDraw
    baseline = big // 2 + int(BASELINE_SHIFT_EM * CELL * SS)
    ImageDraw.Draw(img).text((big // 2, baseline), ch, fill=255, font=font_big, anchor="ms")
    small = img.crop((big // 2 - big // (2 * SS) * SS // SS * SS - 0, 0, 0, 0)) if False else img
    small = img.crop((big // 2 - CELL * SS // 2, big // 2 - CELL * SS // 2,
                      big // 2 + CELL * SS // 2, big // 2 + CELL * SS // 2))
    small = small.resize((CELL, CELL), Image.BOX)
    bits = bytearray(CELL * CELL // 8)
    any_ink = False
    px = small.load()
    for y in range(CELL):
        for x in range(CELL):
            if px[x, y] >= threshold:
                bits[y * CELL // 8 + x // 8] |= 0x80 >> (x % 8)
                any_ink = True
    return bytes(bits) if any_ink else None

def ascii_art(bits):
    rows = []
    for y in range(CELL):
        rows.append("".join("#" if bits[y * CELL // 8 + x // 8] & (0x80 >> (x % 8)) else "." for x in range(CELL)))
    return "\n".join(rows)

def main():
    chars = gb2312_level1()
    chars += [c for c in PUNCT if ord(c) >= 0x80]
    seen = set()
    unique = []
    for c in chars:
        if c not in seen:
            seen.add(c)
            unique.append(c)

    # The .ttc bundles SC/TC/JP/...; pick the "Noto Sans CJK SC" face.
    font_big = None
    for index in range(8):
        try:
            f = ImageFont.truetype(FONT, CELL * SS, index=index)
        except OSError:
            break
        name = " ".join(f.getname())
        if "CJK SC" in name:
            font_big = f
            print(f"face: {name}")
            break
    if font_big is None:
        sys.exit("Noto Sans CJK SC face not found in " + FONT)

    missing = []
    table = []
    for ch in unique:
        bits = render_char(font_big, ch)
        if bits is None:
            # Hairline glyphs (fullwidth bars) fall under the threshold.
            bits = render_char(font_big, ch, threshold=64)
        if bits is None:
            missing.append(ch)
            continue
        table.append((ord(ch), bits))

    print(f"chars: {len(table)} baked, {len(missing)} missing from the font")
    if missing:
        print("missing:", " ".join(missing[:40]))
    table.sort(key=lambda e: e[0])

    cps = ", ".join(f"0x{cp:04X}" for cp, _ in table)
    body = []
    for _, bits in table:
        body.append("    " + " ".join(f"0x{b:02X}" for b in bits) + ",")
    bitmaps = "\n".join(body)

    src = f"""// Generated by firmware/core/gen_cjk_font.py from Noto Sans CJK SC — do not edit.
// 16x16 one-bit-per-pixel glyphs (row-major, MSB first), one for each
// GB2312 level-1 hanzi plus common CJK punctuation. kCjkCodepoints is sorted
// by codepoint: find a glyph with a binary search, then index kCjkBitmaps.
#include "hg/font.hpp"

#include <cstddef>

namespace hg::font {{

const uint16_t kCjkCodepoints[{len(table)}] = {{
    {cps}
}};

const uint8_t kCjkBitmaps[{len(table)} * kCjkBytes] = {{
{bitmaps}
}};

bool cjk_glyph(uint32_t codepoint, const uint8_t** out) {{
  size_t lo = 0, hi = kCjkCount;
  while (lo < hi) {{
    const size_t mid = lo + (hi - lo) / 2;
    if (kCjkCodepoints[mid] < codepoint) lo = mid + 1;
    else hi = mid;
  }}
  if (lo < kCjkCount && kCjkCodepoints[lo] == codepoint) {{
    if (out) *out = &kCjkBitmaps[lo * kCjkBytes];
    return true;
  }}
  return false;
}}

uint32_t utf8_next(std::string_view s, size_t& i) {{
  if (i >= s.size()) return 0;
  const auto c0 = static_cast<unsigned char>(s[i]);
  if (c0 < 0x80) {{
    ++i;
    return c0;
  }}
  size_t len = 0;
  uint32_t cp = 0;
  if ((c0 & 0xE0) == 0xC0) {{
    len = 2;
    cp = c0 & 0x1F;
  }} else if ((c0 & 0xF0) == 0xE0) {{
    len = 3;
    cp = c0 & 0x0F;
  }} else if ((c0 & 0xF8) == 0xF0) {{
    len = 4;
    cp = c0 & 0x07;
  }} else {{
    ++i;
    return 0xFFFD;
  }}
  if (i + len > s.size()) {{
    ++i;
    return 0xFFFD;
  }}
  for (size_t k = 1; k < len; ++k) {{
    const auto cc = static_cast<unsigned char>(s[i + k]);
    if ((cc & 0xC0) != 0x80) {{
      ++i;
      return 0xFFFD;
    }}
    cp = (cp << 6) | (cc & 0x3F);
  }}
  i += len;
  return cp;
}}

}}  // namespace hg::font
"""
    OUT.write_text(src, encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(table)} glyphs, {len(table) * 32} B of bitmaps)")

    for probe in "中国飞襄。囊一aＡ":
        bits = render_char(font_big, probe)
        print(f"--- {probe!r}")
        if bits:
            print(ascii_art(bits))

if __name__ == "__main__":
    main()
